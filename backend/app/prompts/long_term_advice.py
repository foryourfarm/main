"""장기 커리큘럼 서술 프롬프트 — 코드에 흩뿌리지 않고 여기서 버전 관리(CLAUDE.md §13).

`daily_advice.py`와 같은 구조다 — **LLM은 다듬기만 한다.** 위험 판정·수치·기준은 백엔드
룰 엔진이 이미 끝냈고, 규칙 기반 문구(`long_term_advice_service.rule_advice`)가 품질
하한선이다. 그래서 프롬프트에 **[기본 문구]를 통째로 넣는다.**

**단기와 다른 것 세 가지** — 이 셋이 이 파일이 따로 있는 이유다:

1. **시제가 다르다.** 단기는 "오늘 이렇게 하라", 장기는 "앞으로 3개월 이렇게 대비하라".
2. **추정 어미를 지켜야 한다**(`ESTIMATE_TONE_RULE`). 장기 점수는 예보가 아니라 최근 5년
   관측 평균에 3개월전망을 얹은 **이론 추정치**다. 모델이 "9월엔 밤 기온이 12.4℃까지
   떨어집니다"로 단정하면 근사치를 확정 실측처럼 보여주는 것이라 §18-4를 정면으로 어긴다.
   규칙 문구가 이미 "~할 것으로 보입니다"로 쓰므로 여기선 **바꾸지 말라고만** 한다.
3. **상대 월 표현 금지**(`RELATIVE_MONTH_RULE`). 단기의 `RELATIVE_DATE_RULE`과 같은 이유 —
   모델은 오늘이 몇 월인지 모른다. "9월"을 "다음 달"로 바꾸는 것도 계산이라 §18-3에 걸린다.

few-shot 3개는 작물을 서로 다르게 뒀고, `daily_advice`가 쓴 감자·오이·사과와 겹치지 않게
**배·상추 + 사과**로 골랐다. 두 프롬프트를 합쳐 보면 5작물이 고르게 나온다 — 챗봇 v5에서
예시 4개 중 3개가 상추여서 사과밭 질문에 "상추밭과 마찬가지로"가 나온 label bleed 전례가
있다(prompts/chatbot.py).

프롬프트를 바꾸면 PROMPT_VERSION을 올린다(품질 비교·재현용, docs/llm-integration.md §10).
이 값은 캐시 해시에도 들어가므로
(`app/services/advice_cache.py`) **올리면 저장된 문구가 전량 재생성된다** —
프롬프트를 고쳤는데 캐시 때문에 반영이 안 되는 함정을 막기 위한 것이다.
"""

PROMPT_VERSION = "longterm-v1"

# 테스트가 가리키는 앵커. 이 규칙이 프롬프트에서 사라지면 실패한다 — 둘 다 §18-4/§18-3에
# 직접 걸리는 규칙이라 "짧게 다듬는다"는 이유로 조용히 빠지면 안 된다.
ESTIMATE_TONE_RULE = "추정 표현을 확정 표현으로 바꾸지 마라"
RELATIVE_MONTH_RULE = "상대 표현으로 바꾸지 마라"

_SYSTEM = """#명령문
너는 초보 귀농인에게 앞으로 3개월을 어떻게 대비할지 알려주는 농사 도우미다. [입력문]의
[기본 문구]를 초보자가 읽기 쉬운 자연스러운 한국어로 다듬어라.

#제약조건
- [기본 문구]에 담긴 사실(수치·달·기준·위험 종류)을 절대 바꾸거나 빼지 마라. 표현만 다듬는다.
- [기본 문구]에 없는 수치·기준·임계값을 새로 지어내지 마라. "보통 15℃ 이하면" 같은 문장 금지.
- [기본 문구]의 "~할 것으로 보입니다" 같은 추정 표현을 확정 표현으로 바꾸지 마라. 이 값은 예보가 아니라 최근 5년 관측 평균에 3개월전망을 얹은 추정치다. "떨어집니다"가 아니라 "떨어질 것으로 보입니다"로 끝맺어라.
- 달을 "다음 달·두 달 뒤·이번 가을" 같은 상대 표현으로 바꾸지 마라. [기본 문구]에 적힌 "9월" 형태를 그대로 써라. 오늘이 몇 월인지 너는 알 수 없다.
- [작물]로 지정된 작물만 언급하라. 다른 작물을 예로 들거나 비교하지 마라.
- 2~3문장으로 짧게. 번호·기호로 나열하지 말고 자연스러운 문장으로 이어 써라.
- 겁주지 말고 담담하게. 지금부터 무엇을 준비하면 되는지로 끝맺어라.
- 인사말·서론·"알겠습니다" 같은 말 없이 다듬은 문구만 출력하라.

#출력형식
다듬은 문구 2~3문장. 다른 설명 없이 그 문장만.

#예시
[작물] 배
[기본 문구] 10월 야간 최저기온이 2.1℃로 허용 범위(5℃ 이상)에 못 미칠 것으로 보입니다.
[출력] 10월에 밤 기온이 2.1℃까지 내려가 배가 견디는 5℃ 아래로 떨어질 것으로 보입니다. 서리가 내리기 전에 방상팬이나 부직포를 점검해 두시면 좋습니다.

[작물] 상추
[기본 문구] 8월 일 평균기온이 27.3℃로 허용 범위(24℃ 이하)를 벗어날 것으로 보입니다. 9월 일조가 4.1시간으로 허용 범위(5시간 이상)에 못 미칠 것으로 보입니다.
[출력] 8월은 낮 기온이 27.3℃까지 올라 상추가 견디는 24℃를 넘을 것으로 보이고, 9월은 햇빛이 4.1시간으로 다소 부족할 것으로 보입니다. 8월 파종은 차광망을 준비해 미루시고, 9월에는 볕이 잘 드는 자리를 골라 두세요.

[작물] 사과
[기본 문구] 2026년 8~10월에는 큰 기상 위험이 예상되지 않습니다. 현재 생육 단계는 과실비대기입니다.
[출력] 2026년 8월부터 10월까지는 사과밭에 큰 기상 위험이 예상되지 않습니다. 지금은 과실이 커지는 시기이니 물 관리와 웃거름을 평소 일정대로 이어가시면 됩니다.
"""


def build_prompt(crop_name: str, base_text: str) -> str:
    """[기본 문구]를 다듬게 하는 프롬프트. 위험 판정은 이미 끝났고 표현만 맡긴다."""
    return (
        f"{_SYSTEM}\n"
        "#입력문\n"
        f"[작물] {crop_name}\n"
        f"[기본 문구] {base_text}\n"
        "[출력]"
    )
