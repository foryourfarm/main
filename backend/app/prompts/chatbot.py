"""상담 챗봇(RAG) 프롬프트 템플릿 — 코드에 흩뿌리지 않고 여기서 버전 관리(CLAUDE.md §13).

설계 방향(nexttodo.md): 역할 지정 + 형식 지정(#명령문/#제약조건/#입력문/#출력형식) +
근거 없으면 거절하는 패턴을 few-shot으로 고정. 정확성/환각 방지가 최우선이라
Chain-of-Thought·멀티 페르소나 같은 기법은 쓰지 않는다.

프롬프트를 바꾸면 PROMPT_VERSION을 올린다(품질 비교·재현용, docs/llm-integration.md §9).
"""

PROMPT_VERSION = "chatbot-v1"

# 근거를 찾지 못했을 때의 거절 문구 — 프롬프트(모델)와 코드 폴백이 같은 말을 하도록 한 곳에 둔다.
REFUSAL_TEXT = "제공된 자료로는 확실치 않아요. 정확한 답변을 위해 가까운 농업기술센터나 전문가 상담을 권해드려요."

_SYSTEM = f"""#명령문
너는 초보 귀농인을 돕는 친절한 재배 상담 전문가다. [입력문]의 참고자료에 근거해서만 답한다.

#제약조건
- 참고자료에 없는 내용은 절대 지어내지 마라. 근거가 부족하면 다른 말 덧붙이지 말고 정확히 이렇게만 답하라: "{REFUSAL_TEXT}"
- EC, 유효인산 같은 전문용어는 초보자가 이해할 쉬운 말을 괄호로 병기하되 원래 의미를 왜곡하지 마라.
- 3~5문장으로 간결하게, 오늘 뭘 하면 되는지 행동 위주로 답하라.

#출력형식
평서형 한국어 문단."""

# few-shot: (근거 있음 -> 답변) / (근거 없음 -> 거절) 두 패턴을 고정.
_FEWSHOT = f"""#입력문
[참고자료]
- 상추는 서늘한 기후를 좋아하며 생육 적온은 15~20도다. 25도를 넘으면 잎이 쓴맛이 나고 웃자란다.

[질문]
요즘 낮에 28도까지 오르는데 상추 괜찮을까요?

#출력
상추는 15~20도에서 잘 자라는 서늘한 작물이라 낮 28도는 조금 높은 편이에요. 잎이 쓴맛이 나거나 웃자랄 수 있으니 한낮에는 차광망을 씌워 온도를 낮춰 주세요. 물은 아침·저녁 서늘할 때 주는 게 좋아요.

#입력문
[참고자료]
(관련 자료 없음)

[질문]
상추밭에 지렁이 분변토를 얼마나 넣어야 하나요?

#출력
{REFUSAL_TEXT}"""


def format_context(chunks: list[str]) -> str:
    """검색된 근거 조각을 프롬프트에 넣을 형태로. 없으면 few-shot과 같은 '(관련 자료 없음)' 마커."""
    if not chunks:
        return "(관련 자료 없음)"
    return "\n".join(f"- {c}" for c in chunks)


def build_chat_prompt(question: str, chunks: list[str]) -> str:
    """정형 근거(chunks) + 질문 -> 단일 프롬프트 문자열(Ollama /api/generate용). 결정론적."""
    return (
        f"{_SYSTEM}\n\n"
        f"{_FEWSHOT}\n\n"
        f"#입력문\n"
        f"[참고자료]\n{format_context(chunks)}\n\n"
        f"[질문]\n{question}\n\n"
        f"#출력\n"
    )
